number = int(input("Masukkan angka: "))

if number >= 90:
    print("Grade A")
    print("Nilai: ", number)
elif number >= 80:
    print("Grade B")
    print("Nilai: ", number)
elif number >= 70:
    print("Grade C")
    print("Nilai: ", number)
elif number >= 60:
    print("Grade D")
    print("Nilai: ", number)
else:
    print("Grade E")
    print("Nilai: ", number)